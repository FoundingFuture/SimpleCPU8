; AUDIO DEMO. A short tune plays from a MIDI file through three
; synthesized instruments: a plucked tone for the lead and bass, a kick, and a
; snare. The APU renders it on its own real-time clock, so the sound keeps
; playing even while the CPU is paused. A green meter shows the active voices.
; Fire (Z, Ctrl, Space, Enter) restarts the tune.

        ; tone, root A4 (69), lead and bass
        OUT APU_CART_BANK, get_bankbyte(tone)
        OUT APU_CART_HI, get_highbyte(tone)
        OUT APU_CART_LO, get_lowbyte(tone)
        OUT APU_ARG, 10
        OUT APU_ARG2, 40
        OUT APU_NOTE, 69
        OUT APU_SLOT, 0
        OUT APU_CMD, CMD_DEF_SAMPLE
        ; kick, root 36
        OUT APU_CART_BANK, get_bankbyte(kick)
        OUT APU_CART_HI, get_highbyte(kick)
        OUT APU_CART_LO, get_lowbyte(kick)
        OUT APU_ARG, 5
        OUT APU_ARG2, 120
        OUT APU_NOTE, 36
        OUT APU_SLOT, 1
        OUT APU_CMD, CMD_DEF_SAMPLE
        ; snare, root 48
        OUT APU_CART_BANK, get_bankbyte(snare)
        OUT APU_CART_HI, get_highbyte(snare)
        OUT APU_CART_LO, get_lowbyte(snare)
        OUT APU_ARG, 6
        OUT APU_ARG2, 64
        OUT APU_NOTE, 48
        OUT APU_SLOT, 2
        OUT APU_CMD, CMD_DEF_SAMPLE

        ; track 0: lead, melodic, slot 0
        OUT APU_TRACK, 0
        OUT APU_SLOT, 0
        OUT APU_ARG, 0
        OUT APU_CMD, CMD_SET_INSTRUMENT
        ; track 1: bass, melodic, slot 0
        OUT APU_TRACK, 1
        OUT APU_SLOT, 0
        OUT APU_ARG, 0
        OUT APU_CMD, CMD_SET_INSTRUMENT
        ; track 7: the drum kit, keymap by octave (MIDI channel 10 routes here)
        OUT APU_TRACK, 7
        OUT APU_ARG, 1
        OUT APU_CMD, CMD_SET_INSTRUMENT
        OUT APU_SLOT, 1
        OUT APU_ARG, 3        ; octave 3: kick
        OUT APU_CMD, CMD_KEYMAP_ENTRY
        OUT APU_SLOT, 2
        OUT APU_ARG, 4        ; octave 4: snare
        OUT APU_CMD, CMD_KEYMAP_ENTRY

        ; load and start the tune
        OUT APU_CART_BANK, get_bankbyte(tune)
        OUT APU_CART_HI, get_highbyte(tune)
        OUT APU_CART_LO, get_lowbyte(tune)
        OUT APU_CMD, CMD_LOAD_MIDI
        OUT APU_CMD, CMD_PLAY

main:   ; a green voice meter, redrawn each pass
        OUT GPU_COLOR, 0
        OUT GPU_CMD, CMD_CLEAR
        IN A <- APU_VOICES
        LD [nv] <- A
        OUT GPU_X, 8
        OUT GPU_Y, 118
        OUT GPU_CMD, CMD_MOVE_TO
        LD A <- [nv]
        ADD A <- [nv]
        ADD A <- [nv]         ; nv times three
        ADD A <- 8
        LD [t9] <- A
        OUT GPU_COLOR, $1C    ; green
        OUT GPU_CMD, CMD_SET_COLOR
        LD A <- [t9]
        OUTA GPU_X
        OUT GPU_Y, 138
        OUT GPU_CMD, CMD_RECT

        ; fire restarts the tune
        IN A <- IO_CONTROLLER
        AND A <- $70
        JZ nofire
        OUT APU_CMD, CMD_PLAY
nofire: ; replay automatically when the tune ends
        IN A <- APU_STATUS
        AND A <- $FF
        JZ replay
        JMP main
replay: OUT APU_CMD, CMD_PLAY
        JMP main

